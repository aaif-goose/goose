const fs = require("node:fs");
const path = require("node:path");
const {
  LANGUAGES,
  funcAnchor,
  itemAnchor,
  memberAnchor,
  signature,
  variantName,
} = require("../src/components/GdkApiReference/api");

const cell = (value) =>
  String(value).replace(/\|/g, "\\|").replace(/\r?\n/g, "<br />");
const heading = (level, anchor, name) =>
  `<a id="${anchor}"></a>\n\n${"#".repeat(level)} ${name}\n`;

function parameterTable(rows, language, anchor, kind) {
  if (rows.length === 0) return "";
  return [
    "| Name | Type | Default | Description |",
    "| --- | --- | --- | --- |",
    ...rows.map((row) => {
      const name = language.field(row.name);
      const type = language.type(row.type);
      const value =
        row.default === null ? "—" : `\`${language.default(row.default)}\``;
      return `| <a id="${memberAnchor(anchor, kind, row.name)}"></a>\`${name}\` | \`${cell(type)}\` | ${cell(value)} | ${cell(row.docs || "—")} |`;
    }),
    "",
  ].join("\n");
}

function renderFunction(func, language, owner) {
  const anchor = funcAnchor(func, owner);
  return [
    heading(owner ? 4 : 3, anchor, `\`${language.func(func.name)}\``),
    ...(func.docs ? [func.docs, ""] : []),
    `\`\`\`${language.prism}`,
    signature(func, language, owner),
    "```",
    "",
    parameterTable(func.params, language, anchor, "param"),
    ...(func.throws
      ? [`Raises \`${language.errorType(func.throws)}\`.`, ""]
      : []),
  ].join("\n");
}

function renderMarkdown(doc, language) {
  const filename = `api-reference-${language.id}.md`;
  const output = [
    `# ${language.label} API reference`,
    "",
    `Generated from \`${doc.source}\` for \`goose-sdk ${doc.version}\` (documentation series ${doc.docVersion}). Do not edit this file.`,
    "",
    `This is the in-process provider and compaction API, not the full Rust agent runtime. Read the [crate overview](/docs/gdk/reference/index.md) for native Rust APIs.`,
    "",
    `[Versioned copy](/docs/gdk/sdk/${doc.version}/${filename}). Match the API snapshot to your installed package before writing code.`,
    "",
    "## Contents",
    "",
    "- [Functions](#functions)",
    ...doc.items.map((item) => {
      const name =
        item.kind === "error" ? language.errorType(item.name) : item.name;
      return `- [${name}](#${itemAnchor(item)})`;
    }),
    "",
    heading(2, "functions", "Functions"),
    ...doc.functions.map((func) => renderFunction(func, language)),
  ];

  for (const item of doc.items) {
    const anchor = itemAnchor(item);
    const name =
      item.kind === "error" ? language.errorType(item.name) : item.name;
    output.push(
      heading(2, anchor, `\`${name}\``),
      `Kind: ${item.kind}.`,
      "",
      ...(item.docs ? [item.docs, ""] : []),
      parameterTable(item.fields, language, anchor, "field"),
    );
    for (const variant of item.variants) {
      const variantAnchor = memberAnchor(anchor, "variant", variant.name);
      output.push(
        heading(
          3,
          variantAnchor,
          `\`${variantName(item, variant, language)}\``,
        ),
        parameterTable(variant.fields, language, variantAnchor, "field"),
      );
    }
    output.push(
      ...item.methods.map((method) =>
        renderFunction(method, language, item.name),
      ),
    );
  }

  return (
    output
      .join("\n")
      .replace(/\n{3,}/g, "\n\n")
      .trimEnd() + "\n"
  );
}

function generateReferences(data, outputDir) {
  for (const language of LANGUAGES.filter((entry) => entry.id !== "rust")) {
    const filename = `api-reference-${language.id}.md`;
    for (const [index, doc] of data.versions.entries()) {
      const content = renderMarkdown(doc, language);
      const versionDir = path.join(outputDir, doc.version);
      fs.mkdirSync(versionDir, { recursive: true });
      fs.writeFileSync(path.join(versionDir, filename), content);
      if (index === 0)
        fs.writeFileSync(path.join(outputDir, filename), content);
    }
  }
}

if (require.main === module) {
  const data = require("../src/data/gdk-api.json");
  const outputDir = path.join(__dirname, "../static/docs/gdk/sdk");
  generateReferences(data, outputDir);
  console.log(
    `[generate-gdk-api-markdown] Generated Python and Kotlin references in ${outputDir}`,
  );
}

module.exports = { renderMarkdown, generateReferences };
